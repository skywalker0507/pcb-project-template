#!/usr/bin/env python3
"""Read-only, full reachable-Git-object audit. Never prints matching secret values.

Coverage: every object reachable through refs available in a full checkout.
Out of scope: server-only unreachable objects, Git LFS payloads, hidden private
repositories, submodules, proof of legal ownership, third-party license grants.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
MAX_BLOB_BYTES = 50 * 1024 * 1024

STRONG_PATTERNS = {
    "private_key": re.compile(rb"-----BEGIN (?:RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----"),
    "github_token": re.compile(rb"(?:gh[pousr]_|github_pat_)[A-Za-z0-9_]{25,}"),
    "openai_key": re.compile(rb"[s]k-(?:proj-|svcacct-)?[A-Za-z0-9_-]{24,}"),
    "aws_access_key": re.compile(rb"AKIA[0-9A-Z]{16}"),
    "google_api_key": re.compile(rb"AIza[0-9A-Za-z_-]{25,}"),
    "slack_token": re.compile(rb"xox[baprs]-[A-Za-z0-9-]{20,}"),
}
WEAK_PATTERNS = {
    "private_network_address": re.compile(rb"\b(?:10\.(?:\d{1,3}\.){2}\d{1,3}|192\.168\.(?:\d{1,3}\.)\d{1,3}|172\.(?:1[6-9]|2\d|3[01])\.(?:\d{1,3}\.)\d{1,3})\b"),
    "developer_home_path": re.compile(rb"(?:C:\\Users\\[^\\/\s]{2,}\\|/home/[a-zA-Z0-9_.-]{2,}/|/Users/[a-zA-Z0-9_.-]{2,}/)"),
    "email_address": re.compile(rb"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"),
}
ASSIGNED_CREDENTIAL = re.compile(
    rb"(?i)(?:api[_-]?key|secret|password|passwd|access[_-]?token|access[_-]?key)"
    rb"[^\n\r=]{0,40}[:=]\s*[\"']([^\"'\r\n]{8,})[\"']"
)
EXAMPLE = (b"example", b"placeholder", b"dummy", b"changeme", b"your_", b"<", b"https://", b"${", b"os.environ", b"getenv", b"process.env")
PRIVATE_SUFFIXES = {".pem", ".key", ".p12", ".pfx", ".keystore", ".jks"}
PRIVATE_NAMES = {".env", "id_rsa", "id_ed25519", "credentials.json", "secrets.json"}
HARDWARE_SUFFIXES = {".kicad_sym", ".kicad_mod", ".step", ".stp"}
SOURCE_MARKERS = {
    "copyright_or_spdx": re.compile(rb"(?im)(?:Copyright\s*(?:\(c\))?|SPDX-License-Identifier:)"),
    "source_attribution": re.compile(rb"(?im)(?:based on|adapted from|derived from|generated by|original source|easyeda|lcsc)"),
}

def git(*args: str, input_data: bytes | None = None) -> bytes:
    proc = subprocess.run(["git", "-C", str(ROOT), *args], input=input_data, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
    if proc.returncode:
        raise RuntimeError("git command failed: " + " ".join(args) + "; exit " + str(proc.returncode))
    return proc.stdout

def git_objects() -> list[tuple[str, str]]:
    raw = git("rev-list", "--objects", "--all")
    entries = []
    for line in raw.decode("utf-8", "surrogateescape").splitlines():
        head, _, path = line.partition(" ")
        if re.fullmatch(r"[a-f0-9]{40,64}", head):
            entries.append((head, path))
    return entries

def blob_metadata(sha_list: list[str]) -> list[tuple[str, str, int]]:
    raw = git("cat-file", "--batch-check", input_data=("\n".join(sha_list) + "\n").encode("ascii"))
    rows = []
    for line in raw.decode("ascii").splitlines():
        bits = line.split()
        if len(bits) == 3 and bits[1] != "missing":
            rows.append((bits[0], bits[1], int(bits[2])))
    return rows

def blob_bytes(shas: list[str]) -> dict[str, bytes]:
    if not shas:
        return {}
    raw = git("cat-file", "--batch", input_data=("\n".join(shas) + "\n").encode("ascii"))
    result = {}
    pos = 0
    for expected in shas:
        end = raw.find(b"\n", pos)
        if end < 0:
            raise RuntimeError("truncated git cat-file header")
        fields = raw[pos:end].decode("ascii").split()
        if len(fields) != 3 or fields[0] != expected or fields[1] != "blob":
            raise RuntimeError("git cat-file object mismatch")
        size = int(fields[2])
        pos = end + 1
        result[expected] = raw[pos:pos + size]
        pos += size
        if raw[pos:pos + 1] != b"\n":
            raise RuntimeError("git cat-file body delimiter missing")
        pos += 1
    return result

def scan_blob(content: bytes, path: str) -> list[tuple[str, str]]:
    issues = []
    filename = Path(path).name.lower()
    if filename in PRIVATE_NAMES or (filename.startswith(".env.") and filename != ".env.example") or Path(path).suffix.lower() in PRIVATE_SUFFIXES:
        issues.append(("high", "credential_filename"))
    for label, regex in STRONG_PATTERNS.items():
        if regex.search(content):
            issues.append(("high", label))
    for label, regex in WEAK_PATTERNS.items():
        matches = regex.findall(content)
        if label == "email_address":
            matches = [m for m in matches if b"example." not in m.lower() and b"users.noreply.github.com" not in m.lower()]
        if matches:
            issues.append(("review", label))
    for m in ASSIGNED_CREDENTIAL.finditer(content):
        candidate = m.group(1).strip().lower()
        if candidate and not any(x in candidate for x in EXAMPLE):
            # This intentionally over-flags possible literal credentials;
            # a human reviews the source without exposing the value.
            issues.append(("review", "credential_assignment"))
            break
    return issues

def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=ROOT / "build/audit/git-history-audit.json")
    parser.add_argument("--fail-on-high", action="store_true")
    args = parser.parse_args()
    entries = git_objects()
    paths = {sha: path for sha, path in entries}
    metadata = blob_metadata([sha for sha, _ in entries])
    blobs = [(sha, size) for sha, kind, size in metadata if kind == "blob"]
    too_large = [{"object": sha[:12], "path": paths.get(sha, ""), "bytes": size} for sha, size in blobs if size > MAX_BLOB_BYTES]
    searchable = [sha for sha, size in blobs if size <= MAX_BLOB_BYTES]
    findings = []
    provenance = Counter()
    provenance_examples: dict[str, list[str]] = {}
    for i in range(0, len(searchable), 60):
        for sha, data in blob_bytes(searchable[i:i+60]).items():
            path = paths.get(sha, "")
            tags = []
            if Path(path).suffix.lower() in HARDWARE_SUFFIXES:
                tags.append("externally_sourced_hardware_asset_requires_license_check")
            if path == "HARDWARE_SPEC.md" or path.startswith("elec/layout/") and path.endswith((".kicad_pcb", ".kicad_pro", ".kicad_dru")) or path.startswith("src/parts/"):
                tags.append("project_specific_hardware_not_generic_template")
            if SOURCE_MARKERS["copyright_or_spdx"].search(data):
                tags.append("explicit_ownership_or_license_marker")
            if SOURCE_MARKERS["source_attribution"].search(data) and path.startswith(("src/", "scripts/", "docs/", "template-engine/")):
                tags.append("upstream_or_generated_source_reference")
            for label in sorted(set(tags)):
                provenance[label] += 1
                group = provenance_examples.setdefault(label, [])
                if len(group) < 10 and path not in group:
                    group.append(path)
            for severity, category in scan_blob(data, path):
                findings.append({"severity": severity, "category": category, "object": sha[:12], "path": path})
    findings.sort(key=lambda item: (item["severity"] != "high", item["category"], item["path"]))
    refs = git("for-each-ref", "--format=%(refname)").decode("utf-8", "replace").splitlines()
    commit_log = git("log", "--all", "--format=%H%x09%aN%x09%aE", "--no-show-signature").decode("utf-8", "replace").splitlines()
    identities = set()
    for entry in commit_log:
        parts = entry.split("\t")
        if len(parts) == 3:
            identities.add((parts[1], parts[2]))
    summary = {
        "scope": "all locally reachable git objects from fetched refs; not unreachable server objects or external Git LFS objects",
        "refs": refs,
        "reachable_commits": len({e.split("\t")[0] for e in commit_log}),
        "commit_author_identities": len(identities),
        "note": "Git commits can reveal author names/emails. Review original metadata privately before publishing.",
        "git_objects": len(metadata),
        "unique_blobs": len(blobs),
        "scanned_blobs": len(searchable),
        "skipped_large_blobs": too_large,
        "severity_counts": dict(Counter(f["severity"] for f in findings)),
        "category_counts": dict(Counter(f["category"] for f in findings)),
        "findings": findings[:200],
        "findings_truncated": len(findings) > 200,
        "provenance_counts": dict(provenance),
        "provenance_examples": provenance_examples,
        "limitations": [
            "Pattern-based scans cannot guarantee the absence of unknown secrets.",
            "Identical Git blobs share a single SHA; the reported path is one historical path, not necessarily every path.",
            "No legal determination of third-party source ownership or redistribution rights is possible from Git metadata alone.",
            "No network-based comparison to upstream copyright holders is performed."
        ]
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False))
    if args.fail_on_high and (summary["severity_counts"].get("high", 0) or too_large):
        return 1
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
